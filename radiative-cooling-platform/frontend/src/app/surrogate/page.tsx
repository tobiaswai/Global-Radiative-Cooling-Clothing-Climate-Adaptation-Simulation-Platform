"use client";

import Link from "next/link";
import { useEffect, useState } from "react";

import {
  cancelSurrogateDataset, getSurrogateReportUrl, listSurrogateDatasets,
  listSurrogateModels, trainSurrogateModel,
} from "@/lib/api-client";
import { METRIC_LABELS } from "@/lib/optimization-labels";
import { formatRelativeTime } from "@/lib/relative-time";
import type { MetricName } from "@/types/optimization";
import type { SurrogateDataset, SurrogateModel } from "@/types/surrogate";

const ACTIVE_DATASET = new Set(["running", "finalizing"]);
const ACTIVE_MODEL = new Set(["queued", "training"]);

export default function SurrogatePage() {
  const [datasets, setDatasets] = useState<SurrogateDataset[]>([]);
  const [models, setModels] = useState<SurrogateModel[]>([]);
  const [error, setError] = useState("");
  const [busy, setBusy] = useState<string | null>(null);
  const [revision, setRevision] = useState(0);

  useEffect(() => {
    let disposed = false;
    let timer: number | null = null;
    async function load() {
      try {
        const [d, m] = await Promise.all([listSurrogateDatasets(), listSurrogateModels()]);
        if (disposed) return;
        setDatasets(d.items);
        setModels(m.items);
        setError("");
        if (d.items.some((x) => ACTIVE_DATASET.has(x.status)) || m.items.some((x) => ACTIVE_MODEL.has(x.status))) {
          timer = window.setTimeout(load, 5000);
        }
      } catch (caught) {
        if (!disposed) setError(caught instanceof Error ? caught.message : "Unable to load");
      }
    }
    void load();
    return () => {
      disposed = true;
      if (timer !== null) window.clearTimeout(timer);
    };
  }, [revision]);

  async function run(id: string, action: () => Promise<unknown>) {
    setBusy(id);
    try {
      await action();
      setRevision((r) => r + 1);
    } catch (caught) {
      setError(caught instanceof Error ? caught.message : "Request failed");
    } finally {
      setBusy(null);
    }
  }

  return (
    <main className="min-h-screen bg-slate-950 text-white">
      <div className="mx-auto max-w-7xl space-y-8 px-6 py-10">
        <header className="flex flex-wrap items-center justify-between gap-4">
          <div>
            <p className="text-sm text-cyan-400">Machine Learning</p>
            <h1 className="mt-2 text-3xl font-bold">Physics-trained Surrogate Models</h1>
            <p className="mt-3 max-w-4xl text-slate-400">
              Datasets are generated by the physics engine; models are accepted only if leave-one-city and
              leave-one-season errors meet their thresholds. Outside the training domain, or with a stale or
              rejected model, results come from physics.
            </p>
          </div>
          <Link href="/surrogate/sweep" className="rounded-lg bg-cyan-400 px-5 py-2.5 font-semibold text-slate-950">
            Quick sweep
          </Link>
        </header>

        {error && <div className="rounded-lg border border-red-900 bg-red-950 p-4 text-red-300">{error}</div>}

        <section className="overflow-x-auto rounded-2xl border border-slate-800 bg-slate-900">
          <h2 className="p-5 text-xl font-semibold">Datasets</h2>
          <table className="w-full min-w-[60rem] text-left text-sm">
            <thead className="bg-slate-950 text-xs uppercase tracking-wide text-slate-500">
              <tr>
                <th className="px-5 py-3">Name</th><th className="px-5 py-3">Status</th>
                <th className="px-5 py-3">Chunks</th><th className="px-5 py-3">Rows</th>
                <th className="px-5 py-3">Physics</th><th className="px-5 py-3">Created</th>
                <th className="px-5 py-3" />
              </tr>
            </thead>
            <tbody>
              {datasets.map((d) => (
                <tr key={d.id} className="border-t border-slate-800">
                  <td className="px-5 py-3">{d.name}<p className="font-mono text-xs text-slate-500">{d.id.slice(0, 8)}</p></td>
                  <td className="px-5 py-3">{d.status}{d.error_message && <p className="text-xs text-red-300">{d.error_message}</p>}</td>
                  <td className="px-5 py-3">
                    {d.completed_chunks} / {d.total_chunks}
                    {d.failed_chunks > 0 && <span className="ml-2 text-red-300">{d.failed_chunks} failed</span>}
                  </td>
                  <td className="px-5 py-3">{d.row_count.toLocaleString()}</td>
                  <td className="px-5 py-3 font-mono text-xs">{d.model_version}</td>
                  <td className="px-5 py-3 text-slate-400">{formatRelativeTime(d.created_at)}</td>
                  <td className="px-5 py-3 text-right">
                    {(d.status === "completed" || d.status === "partial_completed") && (
                      <button type="button" disabled={busy === d.id}
                        onClick={() => run(d.id, () => trainSurrogateModel({ name: `${d.name} model`, dataset_id: d.id }))}
                        className="rounded-lg border border-cyan-700 px-3 py-1.5 text-cyan-300 disabled:opacity-50">
                        Train model
                      </button>
                    )}
                    {d.status === "running" && (
                      <button type="button" disabled={busy === d.id}
                        onClick={() => run(d.id, () => cancelSurrogateDataset(d.id))}
                        className="rounded-lg border border-red-800 px-3 py-1.5 text-red-300 disabled:opacity-50">
                        Cancel
                      </button>
                    )}
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
          {datasets.length === 0 && (
            <p className="p-5 text-sm text-slate-500">
              No datasets yet. Create one with <span className="font-mono">scripts/run_stage13_experiments.py</span>.
            </p>
          )}
        </section>

        <section className="overflow-x-auto rounded-2xl border border-slate-800 bg-slate-900">
          <h2 className="p-5 text-xl font-semibold">Models</h2>
          <table className="w-full min-w-[60rem] text-left text-sm">
            <thead className="bg-slate-950 text-xs uppercase tracking-wide text-slate-500">
              <tr>
                <th className="px-5 py-3">Name</th><th className="px-5 py-3">Status</th>
                <th className="px-5 py-3">Leave-one-city MAE</th><th className="px-5 py-3">Created</th>
                <th className="px-5 py-3" />
              </tr>
            </thead>
            <tbody>
              {models.map((m) => (
                <tr key={m.id} className="border-t border-slate-800">
                  <td className="px-5 py-3">{m.name}<p className="font-mono text-xs text-slate-500">{m.id.slice(0, 8)}</p></td>
                  <td className="px-5 py-3">
                    {m.status}
                    {m.status === "completed" && (
                      <span className={`ml-2 rounded-full px-2 py-0.5 text-xs ${m.accepted ? "bg-emerald-950 text-emerald-300" : "bg-amber-950 text-amber-300"}`}>
                        {m.accepted ? "accepted" : "rejected"}
                      </span>
                    )}
                    {m.stale && <span className="ml-2 rounded-full bg-red-950 px-2 py-0.5 text-xs text-red-300">stale</span>}
                    {m.error_message && <p className="text-xs text-red-300">{m.error_message}</p>}
                  </td>
                  <td className="px-5 py-3 text-xs text-slate-300">
                    {Object.entries(m.headline_mae).map(([t, v]) => (
                      <p key={t}>{METRIC_LABELS[t as MetricName] ?? t}: <span className="font-mono">{v?.toFixed(4)}</span></p>
                    ))}
                  </td>
                  <td className="px-5 py-3 text-slate-400">{formatRelativeTime(m.created_at)}</td>
                  <td className="space-x-3 px-5 py-3 text-right">
                    {m.status === "completed" && (
                      <>
                        <a href={getSurrogateReportUrl(m.id)} className="text-cyan-300 underline">Report</a>
                        <Link href={`/surrogate/sweep?model=${m.id}`} className="text-cyan-300 underline">Sweep</Link>
                      </>
                    )}
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </section>
      </div>
    </main>
  );
}